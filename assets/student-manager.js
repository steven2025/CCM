/* Student identity is the ID, never a name. All mutations are verified server-side. */
(() => {
  'use strict';
  const escape = value => String(value ?? '').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
  function normalizeId(value) {
    const id = String(value ?? '').normalize('NFKC').trim().toUpperCase();
    if (!/^[A-Z0-9_-]{1,64}$/.test(id)) throw new Error('学号格式无效 / Invalid student ID');
    return id;
  }
  const name = value => String(value ?? '').normalize('NFKC').trim().replace(/\s+/g, ' ');
  function validate(entry) {
    const student = { studentId: normalizeId(entry.studentId), chineseName: name(entry.chineseName), englishName: name(entry.englishName) };
    if (!student.chineseName && !student.englishName) throw new Error('中文名或英文名至少填写一个 / At least one name is required');
    if ([student.chineseName, student.englishName].some(v => v.length > 100 || /[\x00-\x1f\x7f]/.test(v))) throw new Error('姓名过长或包含控制字符 / Invalid name');
    return student;
  }
  function inviteText(entry) {
    return `学生 / Student: ${[entry.chineseName, entry.englishName].filter(Boolean).join(' / ')}\n学号 / Student ID: ${entry.studentId}\n班级 / Class: ${entry.className || '未分班 / Unassigned'}\n邀请码 / Invitation code: ${entry.inviteCode}\n课程 / Course: 跨文化管理 / Cross-cultural Management\n\n请使用学号和邀请码登录。\nSign in with your Student ID and Invitation code.\nhttps://steven2025.github.io/CCM/\n\n请勿分享邀请码。 / Keep your invitation code private.`;
  }
  let excelPromise;
  function loadExcel() {
    if (window.XLSX) return Promise.resolve(window.XLSX);
    if (!excelPromise) excelPromise = new Promise((resolve, reject) => {
      const script = document.createElement('script');
      script.src = './assets/vendor/xlsx.full.min.js';
      script.onload = () => window.XLSX ? resolve(window.XLSX) : reject(new Error('Excel 组件不可用 / Excel parser unavailable'));
      script.onerror = () => { excelPromise = null; script.remove(); reject(new Error('Excel 组件加载失败，请检查部署 / Excel parser failed to load')); };
      document.head.appendChild(script);
    });
    return excelPromise;
  }
  function parseRows(rows, existing) {
    const list = [], errors = [], ids = new Set(existing.map(s => s.studentId));
    if (!rows.length) return { students: list, errors: ['文件为空 / Empty file'] };
    const headers = rows[0].map(value => name(value).toLowerCase());
    const idCol = headers.findIndex(v => /学号|student\s*id/.test(v));
    const cnCol = headers.findIndex(v => /中文名|chinese\s*name/.test(v));
    const enCol = headers.findIndex(v => /英文名|english\s*name/.test(v));
    if (idCol < 0 || cnCol < 0 || enCol < 0) return { students: [], errors: ['请使用学号、中文名、英文名三列表头 / Use the template headers'] };
    rows.slice(1).forEach((row, i) => {
      if (!row.some(value => String(value ?? '').trim())) return;
      try {
        const rawId = row[idCol];
        if (typeof rawId === 'number' && (!Number.isSafeInteger(rawId) || rawId < 0)) throw new Error('学号请以文本填写 / Format the ID as text');
        const student = validate({ studentId: rawId, chineseName: row[cnCol], englishName: row[enCol] });
        if (ids.has(student.studentId)) throw new Error('重复学号 / Duplicate ID: ' + student.studentId);
        ids.add(student.studentId); list.push(student);
      } catch (error) { errors.push(`第 ${i + 2} 行 / Row ${i + 2}: ${error.message}`); }
    });
    if (!list.length && !errors.length) errors.push('没有学生数据 / No student rows');
    if (list.length > 300) errors.push('单次最多导入300人 / Maximum 300 students per import');
    return { students: list, errors };
  }

  function mount(container, api) {
    let students = [], classes = [], currentClass = '*', version = null, busy = false, editing = null, classEditing = null, preview = null, search = '';
    const selected = new Set();
    container.className = 'student-manager';
    container.innerHTML = '<p class="sm-note">学号是唯一身份标识；中英文名至少填一个。邀请码由云端生成，6位且不含0。旧测试账号不再使用。<br>Student ID is unique. Enter at least one name. Codes are generated by the server using six digits from 1–9.</p>' +
      '<div class="sm-toolbar"><button data-action="refresh">刷新 / Refresh</button><button data-action="class-add">＋ 新增班级 / New class</button></div>' +
      '<form class="sm-editor" data-class-editor hidden><h4 data-class-editor-title></h4><label>班级名称 / Class name<input name="className" required maxlength="100" autocomplete="off" placeholder="例如：2026级 IMBA 一班"></label><div class="sm-toolbar"><button type="submit">保存班级 / Save class</button><button type="button" data-action="cancel-class">取消 / Cancel</button></div></form>' +
      '<div class="sm-class-layout"><nav class="sm-classes" data-classes aria-label="班级列表 / Classes"></nav><section class="sm-class-content"><div data-class-heading></div>' +
      '<div class="sm-toolbar"><button data-action="add" data-requires-class>＋ 新增学生 / Add</button><a class="sm-download" href="./assets/templates/student-import-template.xlsx" download="跨文化管理-学生导入模板.xlsx">下载 Excel 模板 / Template</a><button data-action="import" data-requires-class>导入名单 / Import</button><input data-file type="file" accept=".xlsx,.csv" hidden><button data-action="copy-all">复制本组邀请 / Copy group</button></div>' +
      '<p class="sm-note">模板含2行示例，请先删除或替换；学号列请保持文本格式。每批最多300人。<br>Replace or remove the two sample rows. Keep IDs as text. Maximum 300 students per batch.</p>' +
      '<input class="sm-search" data-search placeholder="搜索学号或姓名 / Search ID or name" aria-label="搜索学生 / Search students">' +
      '<div class="sm-toolbar"><span data-selection-count>已选0人 / Selected: 0</span><label>移入班级 / Move to<select data-transfer-target aria-label="目标班级 / Destination class"></select></label><button data-action="transfer">确认分班 / Move selected</button></div>' +
      '<div class="sm-status" role="status" aria-live="polite" data-status>正在读取 / Loading…</div>' +
      '<form class="sm-editor" data-editor hidden><h4 data-editor-title></h4><div class="sm-fields"><label>学号 / Student ID<input name="studentId" required maxlength="64" autocomplete="off"></label><label>中文名 / Chinese name<input name="chineseName" maxlength="100" autocomplete="off"></label><label>英文名 / English name<input name="englishName" maxlength="100" autocomplete="off"></label></div><p class="sm-note">学号按文本保存，保留开头的0。编辑不改变学号。<br>IDs are stored as text; leading zeros are preserved. IDs cannot be edited.</p><div class="sm-toolbar"><button type="submit">确认保存 / Save</button><button type="button" data-action="cancel-edit">取消 / Cancel</button></div></form>' +
      '<section class="sm-preview" data-preview hidden></section><section data-copy-fallback hidden><p>自动复制失败，请手动全选复制 / Copy manually:</p><textarea readonly data-copy-text></textarea></section><div class="sm-table" data-table></div></section></div>';
    const $ = selector => container.querySelector(selector);
    function status(text, error = false) { $('[data-status]').textContent = text; $('[data-status]').classList.toggle('error', error); }
    const className = id => classes.find(item => item.classId === id)?.name || '未分班 / Unassigned';
    const canAdd = () => currentClass !== '*' && (!currentClass || classes.some(item => item.classId === currentClass && !item.archived));
    const groupStudents = () => students.filter(student => currentClass === '*' || (student.classId || '') === currentClass);
    function visibleStudents() {
      const query = search.normalize('NFKC').trim().toLowerCase();
      return groupStudents().filter(student => [student.studentId, student.chineseName, student.englishName].join(' ').normalize('NFKC').toLowerCase().includes(query));
    }
    const invitation = student => inviteText({ ...student, className: className(student.classId) });
    function clearDrafts() {
      editing = null; preview = null; selected.clear();
      $('[data-editor]').hidden = true; $('[data-preview]').hidden = true; $('[data-copy-fallback]').hidden = true;
    }
    function renderClasses() {
      const groups = [{ classId: '*', name: '全部学生 / All students' }, { classId: '', name: '未分班 / Unassigned' }].concat(classes);
      $('[data-classes]').innerHTML = groups.map(item => `<button type="button" data-action="class-select" data-class-id="${escape(item.classId)}" aria-pressed="${item.classId === currentClass}" class="sm-class-button ${item.classId === currentClass ? 'active' : ''}"><span>${escape(item.name)}${item.archived ? ' · 已归档 / Archived' : ''}</span><small>${item.classId === '*' ? students.length : students.filter(s => (s.classId || '') === item.classId).length} 人 / students</small></button>`).join('');
      const activeClass = classes.find(item => item.classId === currentClass);
      $('[data-class-heading]').innerHTML = `<h3>${escape(currentClass === '*' ? '全部学生 / All students' : className(currentClass))}</h3>` +
        (activeClass ? `<div class="sm-toolbar"><button data-action="class-edit">重命名班级 / Rename class</button><button data-action="class-archive">${activeClass.archived ? '恢复班级 / Restore class' : '归档班级 / Archive class'}</button></div>` : '') +
        `<p class="sm-note">${currentClass === '*' ? '请选择左侧班级后新增或导入；现有学生可勾选后批量分班。 / Select a class before adding or importing.' : activeClass?.archived ? '归档仅整理班级，不停用学生。请恢复班级后新增或导入。 / Archiving does not disable accounts. Restore to add students.' : '新增与导入自动归入当前班级；学号在全平台唯一。 / New students join this class. IDs are unique across all classes.'}</p>`;
      const previousTarget = $('[data-transfer-target]').value;
      $('[data-transfer-target]').innerHTML = '<option value="">未分班 / Unassigned</option>' + classes.filter(item => !item.archived).map(item => `<option value="${escape(item.classId)}">${escape(item.name)}</option>`).join('');
      if (classes.some(item => item.classId === previousTarget && !item.archived)) $('[data-transfer-target]').value = previousTarget;
    }
    function renderSelection() {
      $('[data-selection-count]').textContent = `已选${selected.size}人 / Selected: ${selected.size}`;
      const all = $('[data-select-all]'), visible = visibleStudents();
      if (all) { all.checked = !!visible.length && visible.every(s => selected.has(s.studentId)); all.indeterminate = !all.checked && visible.some(s => selected.has(s.studentId)); }
      $('[data-action="transfer"]').disabled = busy || version === null || !selected.size;
    }
    function lock(value) {
      busy = value;
      container.querySelectorAll('button').forEach(button => { button.disabled = value || (version === null && button.dataset.action !== 'refresh'); });
      container.querySelectorAll('select, input, [data-search]').forEach(input => { input.disabled = value || version === null; });
      $('[data-editor]').elements.studentId.disabled = value || version === null || !!editing;
      container.querySelectorAll('[data-requires-class]').forEach(button => { button.disabled = value || version === null || !canAdd(); });
      if ($('[data-confirm-import]')) $('[data-confirm-import]').disabled = value || !preview || !!preview.errors.length || !canAdd();
      renderSelection();
    }
    function render() {
      const filtered = visibleStudents();
      $('[data-table]').innerHTML = '<table><thead><tr><th><input type="checkbox" data-select-all aria-label="选择当前显示学生 / Select visible students"></th><th>学号 / ID</th><th>中文名</th><th>English name</th><th>班级 / Class</th><th>邀请码 / Code</th><th>状态</th><th>操作 / Actions</th></tr></thead><tbody>' + filtered.map(s => `<tr><td><input type="checkbox" data-student-select="${escape(s.studentId)}" aria-label="选择 ${escape(s.studentId)}" ${selected.has(s.studentId) ? 'checked' : ''}></td><td>${escape(s.studentId)}</td><td>${escape(s.chineseName || '—')}</td><td>${escape(s.englishName || '—')}</td><td>${escape(className(s.classId))}</td><td><code>${escape(s.inviteCode)}</code></td><td>${s.active ? '启用 / Active' : '停用 / Inactive'}</td><td><button data-action="copy" data-id="${escape(s.studentId)}">复制信息 / Copy</button><button data-action="edit" data-id="${escape(s.studentId)}">编辑 / Edit</button><button data-action="reset" data-id="${escape(s.studentId)}">重置码 / Reset</button><button data-action="toggle" data-id="${escape(s.studentId)}">${s.active ? '停用 / Disable' : '恢复 / Enable'}</button></td></tr>`).join('') + '</tbody></table>' + `<p class="sm-note">本组显示 ${filtered.length} / ${groupStudents().length} 人 · 全部 ${students.length} 人 · 版本 ${version ?? '—'}</p>`;
      renderClasses();
      lock(busy);
    }
    function accept(result) {
      if (!Array.isArray(result.students) || !Array.isArray(result.classes) || result.schemaVersion !== 2 || !Number.isInteger(result.version)) throw new Error('云函数版本不匹配，请先部署 v22 / Deploy cloud function v22 first');
      students = result.students; classes = result.classes; version = result.version;
      if (result.changedClassId) currentClass = result.changedClassId;
      if (currentClass && currentClass !== '*' && !classes.some(item => item.classId === currentClass)) currentClass = '*';
      clearDrafts();
      render();
    }
    async function refresh() {
      if (busy) return;
      lock(true);
      try { accept(await api('students-list')); status(`已加载 ${students.length} 名学生 / Students loaded`); }
      catch (error) { status(error.message, true); }
      finally { lock(false); }
    }
    async function mutate(action, data, message) {
      if (busy || version === null) return;
      lock(true);
      try { accept(await api(action, { ...data, version })); $('[data-class-editor]').hidden = true; status(message); }
      catch (error) { status(error.message + '\n若网络中断或名单有冲突，请先刷新名单再操作。 / Refresh before retrying after a network error or conflict.', true); }
      finally { lock(false); }
    }
    async function copy(text) {
      try { await navigator.clipboard.writeText(text); status('已复制，请私发给对应学生 / Copied; send privately to the student'); }
      catch { $('[data-copy-fallback]').hidden = false; $('[data-copy-text]').value = text; $('[data-copy-text]').focus(); $('[data-copy-text]').select(); status('请手动复制 / Please copy manually', true); }
    }
    function editor(student) {
      editing = student || null;
      const form = $('[data-editor]'); form.reset(); form.hidden = false;
      $('[data-editor-title]').textContent = student ? '编辑学生 / Edit student' : '新增学生 / Add student';
      for (const field of ['studentId','chineseName','englishName']) form.elements[field].value = student?.[field] || '';
      form.elements.studentId.disabled = !!student;
      form.elements[student ? 'chineseName' : 'studentId'].focus();
    }
    $('[data-search]').addEventListener('input', event => { search = event.target.value; selected.clear(); render(); });
    container.addEventListener('change', event => {
      if (busy) return;
      if (event.target.matches('[data-select-all]')) { visibleStudents().forEach(s => event.target.checked ? selected.add(s.studentId) : selected.delete(s.studentId)); render(); }
      if (event.target.matches('[data-student-select]')) { const id = event.target.dataset.studentSelect; event.target.checked ? selected.add(id) : selected.delete(id); renderSelection(); }
    });
    $('[data-class-editor]').addEventListener('submit', event => {
      event.preventDefault();
      const value = name(event.target.elements.className.value);
      if (!value || value.length > 100) return status('请填写1–100字的班级名称 / Enter a class name (1–100 characters)', true);
      void mutate(classEditing ? 'students-class-edit' : 'students-class-add', { name: value, ...(classEditing ? { classId: classEditing } : {}) }, '班级已保存 / Class saved');
    });
    $('[data-editor]').addEventListener('submit', event => {
      event.preventDefault();
      try {
        const form = event.target;
        const student = validate({ studentId: editing?.studentId || form.elements.studentId.value, chineseName: form.elements.chineseName.value, englishName: form.elements.englishName.value });
        if (!editing && students.some(s => s.studentId === student.studentId)) throw new Error('学号已存在 / Duplicate student ID');
        if (!editing && !canAdd()) throw new Error('请先选择未归档的班级 / Select an active class first');
        void mutate(editing ? 'students-edit' : 'students-add', editing ? student : { students: [student], classId: currentClass }, '保存成功；可复制登录信息 / Saved; login information is ready to copy');
      } catch (error) { status(error.message, true); }
    });
    container.addEventListener('click', event => {
      const button = event.target.closest('button[data-action]');
      if (!button || busy) return;
      const action = button.dataset.action, student = students.find(s => s.studentId === button.dataset.id);
      if (action === 'class-select') {
        currentClass = button.dataset.classId; clearDrafts(); search = ''; $('[data-search]').value = ''; $('[data-class-editor]').hidden = true; render();
        status('已切换班级 / Class selected');
      }
      if (action === 'class-add' || action === 'class-edit') {
        classEditing = action === 'class-edit' ? currentClass : null;
        const form = $('[data-class-editor]'); form.hidden = false;
        $('[data-class-editor-title]').textContent = classEditing ? '重命名班级 / Rename class' : '新增班级 / New class';
        form.elements.className.value = classEditing ? className(classEditing) : ''; form.elements.className.focus();
      }
      if (action === 'cancel-class') $('[data-class-editor]').hidden = true;
      if (action === 'class-archive') {
        const target = classes.find(item => item.classId === currentClass);
        if (target && confirm(`${target.archived ? '恢复' : '归档'}班级“${target.name}”？学生账号和成绩不变。\n${target.archived ? 'Restore' : 'Archive'} this class? Accounts and scores are retained.`)) void mutate('students-class-archive', { classId: target.classId, archived: !target.archived }, '班级状态已更新 / Class status updated');
      }
      if (action === 'transfer' && selected.size) {
        const destination = $('[data-transfer-target]').value;
        if (confirm(`将选中的 ${selected.size} 名学生移入“${className(destination)}”？账号、邀请码与历史成绩不变。\nMove selected students? IDs, codes and scores will not change.`)) void mutate('students-transfer', { studentIds: [...selected], classId: destination }, '分班成功；账号和成绩保持不变 / Students moved; accounts and scores retained');
      }
      if (action === 'refresh') { $('[data-editor]').hidden = true; void refresh(); }
      if (action === 'add' && canAdd()) editor(null);
      if (action === 'cancel-edit') $('[data-editor]').hidden = true;
      if (action === 'edit' && student) editor(student);
      if (action === 'copy' && student) { if (!student.active) return status('此学生已停用 / Student is inactive', true); void copy(invitation(student)); }
      if (action === 'copy-all') {
        const active = groupStudents().filter(s => s.active);
        if (!active.length) return status('没有启用的学生 / No active students');
        if (confirm(`将复制当前分组 ${active.length} 名启用学生的信息（不受姓名搜索影响），请勿发到群聊。继续？\nCopy invitations for this entire group? Do not post private codes to a group chat.`)) void copy(active.map(invitation).join('\n\n──────────\n\n'));
      }
      if (action === 'reset' && student && confirm(`重置 ${student.studentId} 的邀请码？旧码将立即失效。\nReset the code? The old code will stop working.`)) void mutate('students-reset-code', { studentId: student.studentId }, '邀请码已重置，请复制新信息 / Code reset; copy the new invitation');
      if (action === 'toggle' && student && confirm(`${student.active ? '停用' : '恢复'} ${student.studentId}？历史成绩保留。\n${student.active ? 'Disable' : 'Enable'} this student? Scores are retained.`)) void mutate('students-status', { studentId: student.studentId, active: !student.active }, '状态已更新 / Status updated');
      if (action === 'import' && canAdd()) $('[data-file]').click();
      if (action === 'cancel-import') { preview = null; $('[data-preview]').hidden = true; }
      if (action === 'confirm-import' && preview && !preview.errors.length && canAdd() && preview.classId === currentClass) void mutate('students-add', { students: preview.students, classId: preview.classId }, `导入成功 / Import successful`);
    });
    $('[data-file]').addEventListener('change', async event => {
      const file = event.target.files[0]; event.target.value = '';
      if (!file || busy || version === null || !canAdd()) return;
      if (!/\.(xlsx|csv)$/i.test(file.name) || file.size > 2 * 1024 * 1024) return status('请选择不超过2MB的xlsx或CSV / Choose an xlsx or CSV under 2MB', true);
      lock(true);
      try {
        const XLSX = await loadExcel();
        const workbook = XLSX.read(await file.arrayBuffer(), { type: 'array', raw: true, cellText: true, cellFormula: true, sheetRows: 303 });
        const sheet = workbook.Sheets[workbook.SheetNames[0]];
        if (!sheet) throw new Error('未找到工作表 / No worksheet');
        if (XLSX.utils.decode_range(sheet['!fullref'] || sheet['!ref'] || 'A1').e.r > 300) throw new Error('模板最多301行（含表头），请分批导入 / Maximum 300 students plus the header; split into batches');
        if (Object.keys(sheet).some(key => !key.startsWith('!') && sheet[key].f)) throw new Error('模板内请勿使用公式 / Formulas are not allowed');
        const rows = XLSX.utils.sheet_to_json(sheet, { header: 1, defval: '', raw: false });
        preview = parseRows(rows, students);
        preview.classId = currentClass;
        $('[data-preview]').hidden = false;
        $('[data-preview]').innerHTML = '<h4>导入预览 / Import preview → ' + escape(className(currentClass)) + '</h4><p class="sm-note">确认后自动生成邀请码；有错误时整批不提交。学号如被 Excel 去掉开头0，请先在原表修正。<br>Codes are generated on confirmation. Fix all errors first. Check leading zeros carefully.</p>' +
          (preview.errors.length ? '<div class="sm-status error">' + preview.errors.map(escape).join('<br>') + '</div>' : '') +
          '<div class="sm-table"><table><thead><tr><th>学号 / ID</th><th>中文名</th><th>English name</th></tr></thead><tbody>' + preview.students.map(s => `<tr><td>${escape(s.studentId)}</td><td>${escape(s.chineseName)}</td><td>${escape(s.englishName)}</td></tr>`).join('') + '</tbody></table></div>' +
          `<div class="sm-toolbar"><button data-action="confirm-import" data-confirm-import>确认导入 ${preview.students.length} 人 / Confirm import</button><button data-action="cancel-import">取消 / Cancel</button></div>`;
        status(preview.errors.length ? '请修正错误后重新导入 / Fix errors and re-import' : '预览就绪，确认后才保存 / Preview ready; confirm to save', !!preview.errors.length);
      } catch (error) { status(error.message, true); }
      finally { lock(false); }
    });
    render(); void refresh();
    return { refresh };
  }
  window.CCMStudents = { mount, normalizeId, validate, parseRows, inviteText };
})();
